def project_text(directory: Path) -> str:
    """Read the actual input graph and reject missing or unused project sources."""
    directory = directory.resolve()
    visited = set()
    pieces = []

    def visit(path: Path) -> None:
        path = path.resolve()
        if not path.is_relative_to(directory):
            raise ValueError("TeX input outside standalone project: " + str(path))
        if not path.is_file():
            raise ValueError("Missing TeX input: " + str(path))
        if path in visited:
            raise ValueError("Repeated or cyclic TeX input: " + str(path))
        visited.add(path)
        source = re.sub(r"(?<!\\)%[^\n]*", "", path.read_text(encoding="utf-8"))
        pieces.append(source)
        for name in re.findall(r"\\(?:input|include)\{([^}]+)\}", source):
            target = directory / name
            if not target.suffix:
                target = target.with_suffix(".tex")
            visit(target)

    visit(directory / "main.tex")
    unused = set(directory.glob("*.tex")) - visited
    if unused:
        raise ValueError("Unincluded TeX source: " + ", ".join(sorted(p.name for p in unused)))
    return "\n".join(pieces)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = assemble()
    for name, text in output.items():
        target = DEST / name
        if args.check:
            if target.read_text(encoding="utf-8") != text:
                raise SystemExit("Generated v5 source differs: " + name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    # Catch broken assembly references before invoking TeX.
    all_tex = project_text(DEST)
    labels = re.findall(r"\\label(?:\[[^]]+\])?\{([^}]+)\}", all_tex)
    if len(labels) != len(set(labels)):
        raise SystemExit("Duplicate v5 labels")
    refs = {key for group in re.findall(r"\\(?:eqref|[cC]ref|ref)\{([^}]+)\}", all_tex)
            for key in group.split(",")}
    if refs - set(labels):
        raise SystemExit("Missing v5 labels: " + str(sorted(refs - set(labels))))
    cites = {key for group in re.findall(r"\\cite(?:\[[^]]+\])?\{([^}]+)\}", all_tex)
             for key in group.split(",")}
    bibs = set(re.findall(r"\\bibitem\{([^}]+)\}", all_tex))
    if cites - bibs:
        raise SystemExit("Missing v5 citations: " + str(sorted(cites - bibs)))
    if bibs - cites:
        raise SystemExit("Uncited v5 references: " + str(sorted(bibs - cites)))
    print(f"v5: {len(output)} assembled files, {len(labels)} unique labels, "
          f"{len(cites)} resolved citations; inherited source identities match.")


if __name__ == "__main__":
    main()
