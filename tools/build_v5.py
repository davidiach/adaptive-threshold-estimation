"""Assemble v5's inherited proofs with explicit editorial changes.

The original sources are immutable inputs. New exposition lives in paper/v5;
this script generates only the six named inherited-source files.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "paper/v5"
GENERATED = "% Generated by tools/build_v5.py; edit the assembly rules, not this file.\n"

# Equation references in prose may share their spelling with function arguments.
# Protect complete math regions before changing plain parenthesized references.
MATH_REGION = re.compile(
    r"\$\$.*?\$\$|(?<!\\)\$(?:\\.|[^\\$])*\$|\\\[.*?\\\]|\\\(.*?\\\)|"
    r"\\begin\{(?P<mathenv>equation\*?|align\*?|gather\*?|multline\*?|displaymath|math)\}"
    r".*?\\end\{(?P=mathenv)\}", re.S)


def prefix_equation_tags(text: str, prefix: str) -> str:
    tags = set(re.findall(r"\\tag\{([^}]+)\}", text))
    if not tags:
        return text
    references = re.compile(r"(?<![\w}])\((" + "|".join(
        re.escape(tag) for tag in sorted(tags, key=len, reverse=True)) + r")\)")
    def prose(part: str) -> str:
        return references.sub(lambda m: "(" + prefix + m[1] + ")", part)
    pieces = []
    start = 0
    for region in MATH_REGION.finditer(text):
        pieces.extend((prose(text[start:region.start()]), region[0]))
        start = region.end()
    pieces.append(prose(text[start:]))
    return re.sub(r"\\tag\{([^}]+)\}", lambda m: r"\tag{" + prefix + m[1] + "}",
                  "".join(pieces))


def once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError("Editorial anchor is not unique: " + old[:100])
    return text.replace(old, new)


def between(text: str, start: str, end: str) -> str:
    return text[text.index(start):text.index(end)]


def appendix(text: str, prefix: str, tag_prefix: str, heading: str) -> str:
    labels = set(re.findall(r"\\label(?:\[[^]]+\])?\{([^}]+)\}", text))
    # Prefix only internal labels; references to the new main text stay intact.
    def rename(match: re.Match) -> str:
        keys = match[2].split(",")
        return match[1] + "{" + ",".join(
            prefix + key if key in labels else key for key in keys) + "}"
    text = re.sub(r"(\\(?:label(?:\[[^]]+\])?|eqref|[cC]ref|ref))\{([^}]+)\}",
                  rename, text)
    text = prefix_equation_tags(text, tag_prefix)
    # Demote without recursively touching the newly demoted sections.
    text = re.sub(r"\\(subsection|section)(\*?)(?=\{)",
                  lambda m: "\\" + {"section": "subsection",
                                    "subsection": "subsubsection"}[m[1]] + m[2], text)
    text = re.sub(r"\\status\{[^{}\n]*\}\n", "", text)
    text = re.sub(r"\\texttt\{([^{}]+)\}", r"\\nolinkurl{\1}", text)
    # Use one bibliography identity for the same Lee--Valiant paper.
    text = re.sub(r"(\\cite(?:\[[^]]+\])?)\{([^}]+)\}",
                  lambda m: m[1] + "{" + ",".join(
                      "leevaliant" if k == "lv" else k for k in m[2].split(",")) + "}",
                  text)
    return heading + "\n\n" + text.strip() + "\n"


def assemble() -> dict[str, str]:
    manifest = json.loads((DEST / "sources.json").read_text(encoding="utf-8"))
    sources = {}
    for path, expected in manifest["sha256"].items():
        data = (ROOT / path).read_bytes()
        # Git's working-tree line endings may differ across platforms.
        data = data.replace(b"\r\n", b"\n")
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError("Inherited source changed: " + path)
        sources[path] = data.decode("utf-8")
    original = sources["paper/paper.tex"]
    intro = between(original, r"\section{Introduction", r"\section{Model,")
    intro = once(intro,
        "These statements are not\nclaims of instance optimality, rare-event optimality, or a general solution\n"
        "to all nested-expectation problems.",
        "The original arbitrary-margin theorem is not an instance-optimal or\n"
        "rare-event theorem. Section~\\ref{sec:rare} treats a global rarity\n"
        "constraint separately; no general solution to all nested-expectation\n"
        "problems is claimed.")
    intro += r"""
\paragraph{Rare events and the verification boundary.}
With a known upper bound $\theta\le\rho$, positive mass may concentrate
on the most difficult magnitudes. The power-margin rates below and
above exponent two are matched by different constructions. At the
fixed quadratic law, a scale-entropy cost contributes an extra
$\sqrt{1+\log(1+\log(1/\rho))}$ beyond the proposed variational modulus.
Section~\ref{sec:rare} states the current results together; the full
rare-event proofs appear in the appendices. This corrects the earlier
matching-$\Psi$ conjecture rather than assuming it.

The original RMS lower bound is proved in Lean for the actual
hidden-magnitude experiment. The untruncated 713 estimator, variational
optimizer, and critical single-coin base-cost theorem have separate formal
specifications. The matching budget-only upper algorithm, unbiased
converse, and full critical theorem remain paper proofs.
Section~\ref{sec:verification} records the exact scope and links.
"""
    core = between(original, r"\section{Model,", r"\section{Computational verification")
    core = once(core, r"\ \le\ 12665\Iinv^2,", r"\ \le\ 713\Iinv^2,")
    core = once(core, r"$\sup_q\E Y^2\le85\Iinv$ and $\sup_q\E T\le149\Iinv$.",
                r"$\sup_q\E Y^2\le23\Iinv$ and $\sup_q\E T\le31\Iinv$.")
    core = once(core,
        "Sufficiency follows from \\cref{lem:universal}, whose analytic constants give\n"
        "$VW\\le85\\cdot149 I_\\mu^2=12665I_\\mu^2$.",
        "Sufficiency already follows from \\cref{lem:universal}. The improved\n"
        "$713I_\\mu^2$ bound uses the modified classifier proved in \\cref{sec:713}.")
    core = once(core, r"\section{Consequences for power",
                "\\input{constant713}\n\n\\section{Consequences for power")
    core = once(core,
        "An arbitrary-margin law localized to a small target\nprobability is not established here.",
        "The localized theory is developed in \\cref{sec:rare}; a sharp\n"
        "characterization for every magnitude law remains open.")
    core = once(core, "This is distribution-wise minimax optimality:",
        "\\paragraph{Formal scope.}\n"
        "The RMS lower bound in the ordinary hidden-magnitude experiment is\n"
        "proved by \\leanref{Tier6/Full.lean}{minimax\\_lower\\_bound}.\n"
        "The matching upper bound, confidence statement, and stronger\n"
        "revealed- or selected-magnitude claims retain paper-proof status.\n\n"
        "This is distribution-wise minimax optimality:")
    core = once(core, r"\subsection{Unknown magnitude laws under an envelope}",
        "\\noindent\\emph{Verification: the converse and sharp lower coefficient\n"
        "remain paper proofs. The constructive upper bound has the conditional-kernel\n"
        "and separate-family Lean coverage stated in \\cref{sec:713}.}\n\n"
        "\\subsection{Unknown magnitude laws under an envelope}")

    continuation = sources["inputs/next-phase/report/research_note.tex"]
    local = between(continuation, r"\section{Experiment,", r"\section{Prior-art audit}")
    local = re.sub(r"\\begin\{conjecture\}.*?\\end\{conjecture\}",
        lambda _: r"""\paragraph{Correction to the earlier conjecture.}
The proposed arbitrary-law matching-$\Psi$ upper bound is refuted by
Theorem~\ref{thm:v5-critical}. The lower bound and optimizer above remain
valid. No matching replacement for arbitrary laws is supplied here.""",
        local, flags=re.S)
    local = once(local, "It is not the general distribution-blind rare-event algorithm posited in Conjecture~\\ref{conj:full}.",
                 "It does not give a distribution-blind rare-event algorithm for arbitrary laws.")
    local = once(local,
        "These are \\emph{lower-modulus consequences and conjectured full rates}; this note does not supply their matching upper bounds.",
        "The above-two rate is matched in \\cref{app:above-two}; at the quadratic\n"
        "law, \\cref{app:critical} proves the additional scale-entropy factor.")
    local = once(local,
        "An all-purpose $\\rho$-adaptive, distribution-blind upper rule remains the main missing step.",
        "A sharp arbitrary-law replacement remains open; the matching-$\\Psi$\n"
        "upper objective is false by \\cref{thm:v5-critical}.")
    local = local.replace("v4's", "the original").replace("the v4 ", "the original ")
    local = local.replace("The v4 ", "The original ").replace("exact v4 ", "original ")
    local = local.replace("corresponding v4 ", "corresponding original ")
    local = local.replace("clipped v4 ", "clipped original ")
    local = local.replace("as in v4.", "as in the original model.")
    local = local.replace("by v4,", "by \\cref{sec:lower},")
    local = local.replace("from v4,", "from \\cref{sec:minimax-proof},")
    local = local.replace("~\\cite{baseline,mendo}", "~\\cite{haldane,mendo}")
    local = local.replace("~\\cite{baseline}", " (\\cref{sec:classifier,sec:minimax-proof})")
    local = appendix(local, "loc:", "A.", r"""\section{Rare-event localization and margins below two}\label{app:localization}
This appendix supplies the general lower bound, its optimizer, the
below-two matching construction, and a general upper bracket.
The earlier arbitrary-law conjecture has been replaced by its correction.
The published rare-prior input is identified explicitly below.""")

    above_source = sources["research/2026-10-27-route-a/construction.tex"]
    above = between(above_source, r"\section{Claim", r"\paragraph{Reproducible diagnostics.}")
    # Repeated priority commentary is covered in the consolidated introduction.
    above = above[:above.index("\nThe sequential likelihood test,")]
    above = above.replace("The previously unresolved exact-power regime", "Exact-power regime")
    above = appendix(above, "above:", "B.", r"""\section{Asymmetric screening above exponent two}\label{app:above-two}
The upper proof is uniform over the stated envelope and global rarity
class. The matching lower proof cites the published fixed-gap input
and supplies the simulation to variable magnitudes. This appendix
remains a paper argument; the separate 713 kernel theorem is a
different construction.""")

    path = "research/2026-10-27-nonlinear-critical/"
    critical_source = sources[path + "unrestricted.tex"]
    critical = between(critical_source, r"\section{Experiment,", r"\begin{thebibliography}")
    for name in ("base_cost.tex", "affine_comparison.tex", "upper_bound.tex"):
        content = sources[path + name]
        if name == "upper_bound.tex":
            content = "\\section{Critical upper construction}\n" + content[content.index("Put $H="):]
        critical = once(critical, r"\input{" + name + "}", content)
    critical = critical.replace("\\appendix\n", "")
    critical = once(critical, "Sion's theorem now gives",
                    "Sion's theorem~\\cite{sion} now gives")
    critical = once(critical,
        "The upper construction was already available in the separately owned critical\n"
        "note, now at commit \\texttt{a8a8dc49115aabdd1fba8d53d3390eb0a5eee864}; it is\n"
        "reproduced with attribution in the appendix.",
        "The upper construction is reproduced in the final subsection. Its source\n"
        "and the inherited proof identities are recorded in the v5 source manifest.")
    critical = appendix(critical, "crit:", "C.", r"""\section{The full critical quadratic law}\label{app:critical}
This appendix gives the full paper argument, including the upper bound.
Its single-coin variance--null-work theorem, including activation,
observable restarts and scale selection, is Lean-checked in the model
stated in \cref{sec:rare}. The statistical common pair, population
transfer and critical upper construction remain unformalized. Existing
agent review is not independent specialist verification.""")

    bibliography = between(original, r"\begin{thebibliography}", r"\end{thebibliography}")
    def bibitems(text: str) -> dict[str, str]:
        body = between(text, r"\begin{thebibliography}", r"\end{thebibliography}")
        return {m[1]: m[0].strip() for m in re.finditer(
            r"\\bibitem\{([^}]+)\}.*?(?=\\bibitem|\Z)", body, re.S)}
    additional = {**bibitems(continuation), **bibitems(critical_source)}
    # Only new references actually used by the included arguments.
    for key in ("mendo", "jn", "pw", "clq"):
        bibliography += "\n" + additional[key] + "\n"
    bibliography += r"""
\bibitem{sion} M. Sion.
\emph{On general minimax theorems}.
Pacific Journal of Mathematics 8(1):171--176, 1958.
\url{https://msp.org/pjm/1958/8-1/pjm-v8-n1-p14-s.pdf}.
"""
    bibliography += "\n\\end{thebibliography}\n"
    return {name: GENERATED + text.rstrip() + "\n" for name, text in {
        "introduction.tex": intro, "core.tex": core,
        "appendix-localization.tex": local, "appendix-above-two.tex": above,
        "appendix-critical.tex": critical, "references.tex": bibliography,
    }.items()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = assemble()
    for name, text in output.items():
        target = DEST / name
        if args.check:
            if target.read_text(encoding="utf-8") != text:
                raise SystemExit("Generated v5 source differs: " + name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    # Catch broken assembly references before invoking TeX.
    all_tex = "\n".join(p.read_text(encoding="utf-8") for p in DEST.glob("*.tex"))
    labels = re.findall(r"\\label(?:\[[^]]+\])?\{([^}]+)\}", all_tex)
    if len(labels) != len(set(labels)):
        raise SystemExit("Duplicate v5 labels")
    refs = {key for group in re.findall(r"\\(?:eqref|[cC]ref|ref)\{([^}]+)\}", all_tex)
            for key in group.split(",")}
    if refs - set(labels):
        raise SystemExit("Missing v5 labels: " + str(sorted(refs - set(labels))))
    cites = {key for group in re.findall(r"\\cite(?:\[[^]]+\])?\{([^}]+)\}", all_tex)
             for key in group.split(",")}
    bibs = set(re.findall(r"\\bibitem\{([^}]+)\}", all_tex))
    if cites - bibs:
        raise SystemExit("Missing v5 citations: " + str(sorted(cites - bibs)))
    print(f"v5: {len(output)} assembled files, {len(labels)} unique labels, "
          f"{len(cites)} resolved citations; inherited source identities match.")


if __name__ == "__main__":
    main()
