"""Generate the status summaries in README.md and docs/RESULTS.md from status.json.

paper/v6/status.json is the single source for each result's verification
status: tools/build_v6.py writes the v6 abstract's status paragraph, the
introduction's verification-boundary paragraph and the manuscript's status
table from it. This tool renders the same entries, in the same order, between
two marker lines in docs/RESULTS.md and in README.md.

docs/RESULTS.md gets the full Markdown table. Each row gives the result's
summary phrase, else its abstract phrase, else its boundary phrase, then its
status and links to its evidence paths. The optional summary phrase lets the
table name a result fully when the abstract phrase is kept short for the title
page. README.md is the landing page and gets the short form: the counts, each
paper-proof result by the phrase the v6 abstract uses for it, and a link to the
table. Text outside the markers is not touched.

After changing status.json, run this tool; --check fails when a document is
stale. The LaTeX conversion is deliberately narrow and fails closed: inline
math is kept for GitHub's renderer, -- and ~ become an en dash and a space,
and \\cref or \\ref becomes a link to the section that defines the label.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_v6 import (DEST, STATUS, _sentence_case, load_status,  # noqa: E402
                      ordered_status_keys)

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "README.md"
TABLE = ROOT / "docs" / "RESULTS.md"
TARGETS = (SUMMARY, TABLE)
# The heading above the table in docs/RESULTS.md; README.md links to its anchor.
TABLE_HEADING = "## Verification status"
TABLE_ANCHOR = "verification-status"
BEGIN = ("<!-- BEGIN status summary: generated by tools/build_status_docs.py "
         "from paper/v6/status.json; do not edit by hand -->")
END = "<!-- END status summary -->"
STATUS_LABELS = {"lean": "Lean-checked", "paper": "Paper proof"}
REFERENCE = re.compile(r"\\c?ref\{([^{}]+)\}")
SECTION = re.compile(r"\\(?:sub){0,2}section\*?\{")


def _link(target: Path, document: Path) -> str:
    return os.path.relpath(target, document.parent).replace(os.sep, "/")


def _braced(text: str, start: int) -> str:
    """The balanced-brace argument whose opening brace precedes `start`."""
    depth = 1
    for index in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[index], 0)
        if depth == 0:
            return text[start:index]
    raise ValueError("Unbalanced section title")


def section_for(label: str, sources: Path = DEST) -> tuple[Path, str]:
    """The v6 source file defining `label`, and the title of its section."""
    found = []
    for path in sorted(sources.glob("*.tex")):
        text = path.read_text(encoding="utf-8")
        position = text.find("\\label{" + label + "}")
        if position >= 0:
            found.append((path, text, position))
    if len(found) != 1:
        raise ValueError(f"Label {label!r} is defined {len(found)} times in {sources}")
    path, text, position = found[0]
    heads = [m for m in SECTION.finditer(text) if m.start() <= position]
    if not heads:
        raise ValueError(f"No section title precedes label {label!r} in {path.name}")
    return path, _braced(text, heads[-1].end())


def latex_to_markdown(phrase: str, document: Path, sources: Path = DEST) -> str:
    """Convert one status phrase, keeping inline math, and fail on anything else."""
    parts = re.split(r"(?<!\\)(\$[^$]*\$)", phrase)
    out = []
    for part in parts:
        if part.startswith("$") and part.endswith("$") and len(part) > 1:
            if "|" in part:
                raise ValueError(f"A table cell cannot contain | in math: {phrase!r}")
            out.append(part)
            continue
        part = part.replace("--", "\u2013").replace("~", " ")

        def reference(match: re.Match) -> str:
            path, title = section_for(match[1], sources)
            text = latex_to_markdown(title, document, sources)
            return f"[{text}]({_link(path, document)})"

        part = REFERENCE.sub(reference, part)
        # A converted title can hold a link; only the remainder must be plain text.
        bare = re.sub(r"\[[^\]]*\]\([^)]*\)", "", part)
        if re.search(r"[\\{}|]", bare):
            raise ValueError(f"Unsupported LaTeX in status phrase: {phrase!r}")
        out.append(part)
    return "".join(out)


def _evidence_label(path: str) -> str:
    parts = Path(path).parts
    if parts[:2] == ("lean", "ThresholdHC"):
        return "/".join(parts[2:])
    if parts[0] == "results" and len(parts) >= 2:
        return parts[1] + " record"
    return parts[-1]


def ordered_keys(status: dict) -> list[str]:
    """Results in the order of the manuscript's status table."""
    return ordered_status_keys(status)


def render(status: dict, document: Path, sources: Path = DEST) -> str:
    results = status["results"]
    keys = ordered_keys(status)
    counts = {kind: sum(results[k]["status"] == kind for k in keys) for kind in STATUS_LABELS}
    source = _link(STATUS, document)
    lines = [
        BEGIN,
        f"The [status source]({source}) of the v6 abstract lists {len(keys)} results: "
        f"{counts['lean']} Lean-checked and {counts['paper']} with paper proofs only. "
        "Run `python tools/build_status_docs.py` after changing it.",
        "",
        "| Result | Status | Evidence |",
        "|---|---|---|",
    ]
    for key in keys:
        result = results[key]
        phrase = result.get("summary") or result.get("abstract") or result["boundary"]
        evidence = " · ".join(f"[{_evidence_label(p)}]({_link(ROOT / p, document)})"
                              for p in result["evidence"])
        lines.append(f"| {_sentence_case(latex_to_markdown(phrase, document, sources))} "
                     f"| {STATUS_LABELS[result['status']]} | {evidence} |")
    lines.append(END)
    return "\n".join(lines) + "\n"


def render_summary(status: dict, document: Path, sources: Path = DEST) -> str:
    """The landing page's short form: the counts, each paper proof by name, the table's link."""
    results = status["results"]
    keys = ordered_keys(status)
    # As in the v6 abstract: a paper proof is named by its abstract phrase, else its
    # boundary phrase. The fuller summary phrase is for the table only.
    paper = [latex_to_markdown(results[k].get("abstract") or results[k]["boundary"],
                               document, sources)
             for k in keys if results[k]["status"] == "paper"]
    if not paper:
        counts = f"Lean checks all {len(keys)} results that the v6 paper tracks."
    else:
        noun = "has a paper proof" if len(paper) == 1 else "have paper proofs"
        counts = (f"The v6 paper tracks {len(keys)} results. Lean checks {len(keys) - len(paper)} "
                  f"of them; {len(paper)} {noun} only: " + "; ".join(paper) + ".")
    table = _link(TABLE, document) + "#" + TABLE_ANCHOR
    lines = [
        BEGIN,
        f"{counts} The [results guide]({table}) lists every result with its status and "
        f"evidence. Both are generated from the [status source]({_link(STATUS, document)}).",
        END,
    ]
    return "\n".join(lines) + "\n"


def block_for(status: dict, document: Path) -> str:
    """The landing page gets the short form; every other document gets the table."""
    return render_summary(status, document) if document == SUMMARY else render(status, document)


def replace_block(text: str, block: str, name: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError(f"{name} needs exactly one status-summary BEGIN and END marker")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    if end < start:
        raise ValueError(f"{name} has the status-summary markers out of order")
    if text[end:end + 1] == "\n":
        end += 1
    return text[:start] + block + text[end:]


def update(status: dict, documents: tuple[Path, ...], write: bool) -> list[Path]:
    """Regenerate each document's summary; return those whose summary was stale."""
    stale = []
    for document in documents:
        raw = document.read_bytes()
        if b"\r\n" in raw:
            raise ValueError(f"{document.name} must keep LF line endings")
        text = raw.decode("utf-8")
        if document == TABLE and TABLE_HEADING + "\n" not in text:
            raise ValueError(f"{document.name} needs the heading {TABLE_HEADING!r} above its table")
        updated = replace_block(text, block_for(status, document), document.name)
        if updated != text:
            stale.append(document)
            if write:
                document.write_bytes(updated.encode("utf-8"))
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail instead of writing when a summary is stale")
    args = parser.parse_args(argv)
    stale = [p.relative_to(ROOT).as_posix()
             for p in update(load_status(), TARGETS, write=not args.check)]
    if args.check and stale:
        print("Stale status summaries: " + ", ".join(stale))
        print("Run python tools/build_status_docs.py and commit the result.")
        return 1
    print(("Updated: " + ", ".join(stale)) if stale and not args.check
          else "Status summaries match paper/v6/status.json.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
