def demote(text: str) -> str:
    # Demote without recursively touching the newly demoted sections.
    return re.sub(r"\\(subsection|section)(\*?)(?=\{)",
                  lambda m: "\\" + {"section": "subsection",
                                    "subsection": "subsubsection"}[m[1]] + m[2], text)


def load_sources() -> dict[str, str]:
    manifest = json.loads((DEST / "sources.json").read_text(encoding="utf-8"))
    sources = {}
    for path, expected in manifest["sha256"].items():
        data = (ROOT / path).read_bytes()
        # Several inherited files use CRLF; hashes are of LF-normalized bytes.
        data = data.replace(b"\r\n", b"\n")
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError("Inherited source changed: " + path)
        sources[path] = data.decode("utf-8")
    return sources


