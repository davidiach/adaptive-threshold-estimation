def once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError("Editorial anchor is not unique: " + old[:100])
    return text.replace(old, new)


def between(text: str, start: str, end: str) -> str:
    begin = text.index(start)
    return text[begin:text.index(end, begin + len(start))]


def labels(text: str) -> set[str]:
    return set(LABEL.findall(text))


def rekey(text: str, mapping: dict[str, str]) -> str:
    """Rename label and reference keys listed in `mapping`; keep the others."""
    def rename(match: re.Match) -> str:
        keys = match[2].split(",")
        return match[1] + "{" + ",".join(mapping.get(key, key) for key in keys) + "}"
    return KEYED.sub(rename, text)


def recite(text: str, mapping: dict[str, str]) -> str:
    def rename(match: re.Match) -> str:
        keys = match[2].split(",")
        return match[1] + "{" + ",".join(mapping.get(key, key) for key in keys) + "}"
    return CITE.sub(rename, text)


def demote(text: str) -> str:
    # Demote without recursively touching the newly demoted sections.
    return re.sub(r"\\(subsection|section)(\*?)(?=\{)",
                  lambda m: "\\" + {"section": "subsection",
                                    "subsection": "subsubsection"}[m[1]] + m[2], text)


def load_sources() -> dict[str, str]:
    manifest = json.loads((DEST / "sources.json").read_text(encoding="utf-8"))
    sources = {}
    for path, expected in manifest["sha256"].items():
        data = (ROOT / path).read_bytes()
        # Several inherited files use CRLF; hashes are of LF-normalized bytes.
        data = data.replace(b"\r\n", b"\n")
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError("Inherited source changed: " + path)
        sources[path] = data.decode("utf-8")
    return sources


