def bibitems(text: str) -> dict[str, str]:
    body = between(text, r"\begin{thebibliography}", r"\end{thebibliography}")
    return {m[1]: m[0].strip() for m in re.finditer(
        r"\\bibitem\{([^}]+)\}.*?(?=\\bibitem|\Z)", body, re.S)}


def bibliography(sources: dict[str, str]) -> str:
    text = sources[V5 + "references.tex"].replace(
        "% Generated by tools/build_v5.py; edit the assembly rules, not this file.\n", "")
    general = bibitems(sources[GL + "main.tex"])
    finite = bibitems(sources[FG + "references.tex"])
    additional = [general["cl16"], finite["hoeffding"], general["bv"], general["cs"], finite["akl"]]
    end = text.rindex(r"\end{thebibliography}")
    return text[:end].rstrip() + "\n\n" + "\n\n".join(additional) + "\n\n" + text[end:]


def assemble() -> dict[str, str]:
    sources = load_sources()
    output = {}
    output.update(v5_material(sources))
    general_law_files = general_law(sources)
    finite_gap_files = finite_gap(sources)
    output.update(general_law_files)
    output.update(finite_gap_files)
    output["references.tex"] = bibliography(sources)
    # Several former main-text sections of the rare-event papers are appendices here.
    rare = set(general_law_files) | set(finite_gap_files)
    in_appendix = {name for name in rare if name.startswith("appendix-")}
    in_appendix |= {"finite-lower.tex", "finite-upper.tex", "finite-assembly.tex"}
    appendices = {key for name in in_appendix
                  for key in re.findall(r"\\(?:sub)?section\{[^}]*\}\\label\{([^}]+)\}", output[name])}
    appendices |= {"sec:matching-lower", "fg:sec:matching-lower"}
    for name in rare:
        output[name] = re.sub(r"Section~\\ref\{([^}]+)\}",
                              lambda m: ("Appendix" if m[1] in appendices else "Section")
                              + "~\\ref{" + m[1] + "}", output[name])
    # Trailing spaces carry no meaning at a TeX line end.
    return {name: GENERATED + "\n".join(line.rstrip() for line in text.rstrip().split("\n")) + "\n"
            for name, text in output.items()}


def project_text(directory: Path) -> str:
    """Read the actual input graph and reject missing or unused project sources."""
    directory = directory.resolve()
    visited = set()
    pieces = []

    def visit(path: Path) -> None:
        path = path.resolve()
        if not path.is_relative_to(directory):
            raise ValueError("TeX input outside standalone project: " + str(path))
        if not path.is_file():
            raise ValueError("Missing TeX input: " + str(path))
        if path in visited:
            raise ValueError("Repeated or cyclic TeX input: " + str(path))
        visited.add(path)
        source = re.sub(r"(?<!\\)%[^\n]*", "", path.read_text(encoding="utf-8"))
        pieces.append(source)
        for name in re.findall(r"\\(?:input|include)\{([^}]+)\}", source):
            target = directory / name
            if not target.suffix:
                target = target.with_suffix(".tex")
            visit(target)

    visit(directory / "main.tex")
    unused = set(directory.glob("*.tex")) - visited
    if unused:
        raise ValueError("Unincluded TeX source: " + ", ".join(sorted(p.name for p in unused)))
    return "\n".join(pieces)


def check_project(all_tex: str) -> tuple[int, int]:
    found = LABEL.findall(all_tex)
    duplicates = sorted({key for key in found if found.count(key) > 1})
    if duplicates:
        raise SystemExit("Duplicate v6 labels: " + str(duplicates))
    refs = {key for group in re.findall(r"\\(?:eqref|[cC]ref|ref)\{([^}]+)\}", all_tex)
            for key in group.split(",")}
    if refs - set(found):
        raise SystemExit("Missing v6 labels: " + str(sorted(refs - set(found))))
    cites = {key for group in CITE.findall(all_tex) for key in group[1].split(",")}
    bibs = set(re.findall(r"\\bibitem\{([^}]+)\}", all_tex))
    if cites - bibs:
        raise SystemExit("Missing v6 citations: " + str(sorted(cites - bibs)))
    if bibs - cites:
        raise SystemExit("Uncited v6 references: " + str(sorted(bibs - cites)))
    begins = re.findall(r"\\begin\{([^}]+)\}", all_tex)
    ends = re.findall(r"\\end\{([^}]+)\}", all_tex)
    for name in set(begins) | set(ends):
        if begins.count(name) != ends.count(name):
            raise SystemExit("Unbalanced v6 environment: " + name)
    return len(found), len(cites)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = assemble()
    for name, text in output.items():
        target = DEST / name
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                raise SystemExit("Generated v6 source differs: " + name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    # Catch broken assembly references before invoking TeX.
    label_count, cite_count = check_project(project_text(DEST))
    print(f"v6: {len(output)} assembled files, {label_count} unique labels, "
          f"{cite_count} resolved citations; inherited source identities match.")


if __name__ == "__main__":
    main()
