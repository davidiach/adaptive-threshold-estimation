STATUS_KINDS = ("lean", "paper")
STATUS_VENUES = ("abstract", "boundary")
# Status belongs in the "status" field, never in a phrase or a fixed sentence.
STATUS_WORDS = re.compile(r"(?-i:\bLean)|paper[\s~-]+proofs?|\bchecked\b|\bverified\b"
                          r"|\bprov(?:ed|es|en)\b|formali[sz]ed|mechani[sz]ed", re.IGNORECASE)
UNESCAPED_PERCENT = re.compile(r"(?<!\\)%")


def _reject_duplicates(pairs: list) -> dict:
    keys = [key for key, _ in pairs]
    duplicates = sorted({key for key in keys if keys.count(key) > 1})
    if duplicates:
        raise ValueError("Duplicate keys in status source: " + ", ".join(duplicates))
    return dict(pairs)


def load_status(path: Path = STATUS) -> dict:
    """Read and validate the single source for the manuscript's status sentences."""
    return validate_status(json.loads(path.read_text(encoding="utf-8"),
                                      object_pairs_hook=_reject_duplicates))


def _check_tex(text, where: str) -> None:
    if not isinstance(text, str) or not text.strip():
        raise ValueError(f"{where} must be a non-empty string")
    if UNESCAPED_PERCENT.search(text):
        raise ValueError(f"{where} contains an unescaped %: {text!r}")
    if text.count("{") != text.count("}") or len(re.findall(r"(?<!\\)\$", text)) % 2:
        raise ValueError(f"{where} has unbalanced braces or math: {text!r}")
    if STATUS_WORDS.search(text):
        raise ValueError(f"Status wording outside the status field in {where}: {text!r}")


def _check_evidence(key: str, result: dict) -> None:
    evidence = result.get("evidence")
    if not isinstance(evidence, list) or not evidence:
        raise ValueError(f"Status of {key} needs a non-empty list of evidence paths")
    root = ROOT.resolve()
    tops = set()
    for item in evidence:
        if (not isinstance(item, str) or not item or Path(item).anchor
                or ".." in Path(item).parts):
            raise ValueError(f"Evidence for {key} must be relative repository paths: {item!r}")
        path = (root / item).resolve()
        if path == root or not path.is_relative_to(root) or not path.exists():
            raise ValueError(f"Evidence for {key} is not an existing path in the repository: {item!r}")
        tops.add(path.relative_to(root).parts[0])
    if result["status"] == "lean" and not tops & {"lean", "results"}:
        raise ValueError(f"Lean status of {key} needs evidence under lean/ or results/")


def validate_status(status: dict) -> dict:
    if not isinstance(status, dict) or set(status) != {"description", "results", *STATUS_VENUES}:
        raise ValueError("Status source needs exactly: description, results, "
                         + ", ".join(STATUS_VENUES))
    results = status["results"]
    if not isinstance(results, dict) or not results:
        raise ValueError("Status source needs a non-empty results object")
    for key, result in results.items():
        if not isinstance(result, dict) or result.get("status") not in STATUS_KINDS:
            raise ValueError(f"Status of {key} must be one of {STATUS_KINDS}")
        unknown = set(result) - {"status", "evidence", "verification_rows", "summary",
                                 *STATUS_VENUES}
        if unknown:
            raise ValueError(f"Unknown fields for {key}: {sorted(unknown)}")
        _check_evidence(key, result)
        rows = result.get("verification_rows", [])
        if not isinstance(rows, list) or not all(isinstance(r, str) and r.strip() for r in rows):
            raise ValueError(f"verification_rows of {key} must be a list of row labels")
        for venue in STATUS_VENUES:
            if venue in result:
                _check_tex(result[venue], f"the {venue} phrase of {key}")
        # An optional fuller phrase for the generated status tables: the README
        # and results guide (tools/build_status_docs.py) and the manuscript's
        # status table. The generated sentences never print it.
        if "summary" in result:
            _check_tex(result["summary"], f"the summary phrase of {key}")
    used = set()
    for venue in STATUS_VENUES:
        if not isinstance(status[venue], list) or not status[venue]:
            raise ValueError(f"The {venue} needs a non-empty list of items")
        seen = set()
        for item in status[venue]:
            if isinstance(item, dict) and set(item) == {"text"}:
                _check_tex(item["text"], f"a {venue} text item")
            elif (isinstance(item, dict) and "results" in item and set(item) <= {"results", "suffix"}
                  and isinstance(item["results"], list) and item["results"]):
                for key in item["results"]:
                    if key not in results or venue not in results[key]:
                        raise ValueError(f"No {venue} phrase for status entry {key}")
                    if key in seen:
                        raise ValueError(f"Status entry {key} repeated in the {venue}")
                    seen.add(key)
                if "suffix" in item:
                    _check_tex(item["suffix"], f"a {venue} suffix")
            else:
                raise ValueError(f"Malformed {venue} status item: {item}")
        phrased = {key for key, result in results.items() if venue in result}
        if phrased != seen:
            raise ValueError(f"Entries with a {venue} phrase but not listed there: "
                             + ", ".join(sorted(phrased - seen)))
        used |= seen
    if set(results) - used:
        raise ValueError("Unused status entries: " + ", ".join(sorted(set(results) - used)))
    return status


LEAN_CITATION = re.compile(r"\\[a-z]*leanref\{|lean/ThresholdHC/")


def verification_rows(tex: str) -> dict[str, str]:
    """Rows of the Section 18 claim table, keyed by their first cell."""
    body = tex[tex.index("\\begin{longtable}"):tex.index("\\end{longtable}")]
    if "\\endhead" in body:
        body = body[body.index("\\endhead") + len("\\endhead"):]
    rows = {}
    for chunk in re.split(r"\\\\\[5pt\]", body):
        if "&" in chunk:
            label, text = chunk.split("&", 1)
            rows[label.strip().splitlines()[-1].strip()] = text
    return rows


def check_verification_rows(status: dict, tex: str) -> None:
    """Section 18 must agree with status.json for every result mapped to a table row."""
    rows = verification_rows(tex)
    for key, result in status["results"].items():
        for label in result.get("verification_rows", []):
            if label not in rows:
                raise ValueError(f"Section 18 has no claim row {label!r} for {key}")
            text = rows[label]
            if result["status"] == "lean" and not LEAN_CITATION.search(text):
                raise ValueError(f"Section 18 row {label!r} cites no Lean source, "
                                 f"but status.json marks {key} Lean-checked")
            if result["status"] == "paper" and ("paper" not in text or LEAN_CITATION.search(text)):
                raise ValueError(f"Section 18 row {label!r} must say paper proof and cite no "
                                 f"Lean source, because status.json marks {key} as a paper proof")


def has_list_comma(phrase: str) -> bool:
    """True if a comma appears outside braces and inline math."""
    depth, math = 0, False
    for char in phrase:
        if char == "$":
            math = not math
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        elif char == "," and depth == 0 and not math:
            return True
    return False


def join_phrases(phrases: list[str]) -> str:
    if len(phrases) == 1:
        return phrases[0]
    if any(has_list_comma(phrase) for phrase in phrases):
        return "; ".join(phrases[:-1]) + "; and " + phrases[-1]
    # A serial comma keeps items that contain "and" from running together.
    serial = len(phrases) > 2 and any(" and " in phrase for phrase in phrases)
    return ", ".join(phrases[:-1]) + (", and " if serial else " and ") + phrases[-1]


def status_text(status: dict, venue: str) -> str:
    """One venue's status sentences: each group is split by its entries' status.

    Phrases are always used as objects, so a status change needs no new wording:
    "Lean checks X." or "For X, the manuscript gives paper proofs only."
    """
    results = status["results"]
    sentences = []
    lean_before = False
    for item in status[venue]:
        if "text" in item:
            sentences.append(item["text"])
            continue
        suffix = item.get("suffix", "")
        lean = [results[k][venue] for k in item["results"] if results[k]["status"] == "lean"]
        paper = [results[k][venue] for k in item["results"] if results[k]["status"] == "paper"]
        if lean:
            lead = "Lean also checks " if lean_before else "Lean checks "
            sentences.append(lead + join_phrases(lean) + suffix + ".")
            lean_before = True
        if paper:
            sentences.append("For " + join_phrases(paper) + suffix
                             + ", the manuscript gives paper proofs only.")
    return textwrap.fill(" ".join(sentences), width=74, break_long_words=False,
                         break_on_hyphens=False)


def ordered_status_keys(status: dict) -> list[str]:
    """Results in abstract order, then those that appear only in the boundary."""
    keys: list[str] = []
    for venue in STATUS_VENUES:
        for item in status[venue]:
            for key in item.get("results", []):
                if key not in keys:
                    keys.append(key)
    return keys


def abstract_status_text(status: dict) -> str:
    """The abstract's status sentences: a count, then each paper proof by name.

    The abstract counts the Lean-checked results and names only the results
    that have paper proofs, so it does not grow with the list of checked
    results. The status table lists every result; the boundary paragraph and
    Section 18 give the scopes. Fixed sentences of the abstract venue follow.
    """
    results = status["results"]
    keys = ordered_status_keys(status)
    paper = [results[key].get("abstract") or results[key]["boundary"]
             for key in keys if results[key]["status"] == "paper"]
    checked = len(keys) - len(paper)
    listed = f"the {len(keys)} results listed in \\cref{{tab:status}}"
    scope = ", each in the scope recorded in \\cref{sec:verification}"
    sentences = []
    if not paper:
        sentences.append(f"Lean checks all {len(keys)} results listed in "
                         f"\\cref{{tab:status}}{scope}.")
    elif checked:
        sentences.append(f"Lean checks {checked} of {listed}{scope}.")
    if paper:
        sentences.append("For " + join_phrases(paper)
                         + ", the manuscript gives paper proofs only.")
    sentences += [item["text"] for item in status["abstract"] if "text" in item]
    return textwrap.fill(" ".join(sentences), width=74, break_long_words=False,
                         break_on_hyphens=False)


def _sentence_case(text: str) -> str:
    text = text[4:] if text.startswith("the ") else text
    return text[:1].upper() + text[1:]


SECTION_LABEL = re.compile(r"\\(?:sub){0,2}section\{.*?\}\s*\\label\{([^}]+)\}", re.S)


def _proof_location(paths: list[str], texts: dict[str, str]) -> str:
    """A reference to the first labelled section of each v6 source in `paths`.

    A paper proof kept outside the manuscript has no such source; its row
    then points to Section 18, which describes it.
    """
    found = []
    for path in paths:
        name = Path(path).name
        if Path(path).parent.as_posix() != "paper/v6" or not name.endswith(".tex"):
            continue
        text = texts[name] if name in texts else (DEST / name).read_text(encoding="utf-8")
        match = SECTION_LABEL.search(text)
        if not match:
            raise ValueError("No labelled section in paper-proof evidence " + path)
        found.append("\\cref{" + match[1] + "}")
    return "\\newline ".join(found) or "See \\cref{sec:verification}"


def status_table(status: dict, texts: dict[str, str] | None = None) -> str:
    """Every tracked result, grouped by status, with its source.

    The row text is the summary phrase, else the abstract phrase, else the
    boundary phrase, as in the README table of tools/build_status_docs.py.
    A Lean-checked row lists its modules relative to lean/ThresholdHC; they
    are not links, because Section 18 holds the links to fixed source
    revisions. A paper-proof row refers to the section that holds the proof.
    `texts` supplies assembled sources that may not be on disk yet.
    """
    results = status["results"]
    keys = ordered_status_keys(status)
    prefix = "lean/ThresholdHC/"
    head = "Result & Source\\\\\n\\midrule\n"
    lines = [
        "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.55\\textwidth}"
        ">{\\raggedright\\arraybackslash\\footnotesize}p{0.41\\textwidth}@{}}",
        f"\\caption{{Verification status of the {len(keys)} results this paper tracks. "
        "For a result checked in Lean the source is its modules, relative to "
        "\\texttt{lean/ThresholdHC/}; for a paper proof it is the location of the "
        "proof. \\Cref{sec:verification} states each formal scope and links the "
        "fixed source revisions.}\\label{tab:status}\\\\",
        "\\toprule\n" + head + "\\endfirsthead",
        "\\toprule\n" + head + "\\endhead",
    ]
    groups = (("lean", "Checked in Lean"), ("paper", "Paper proof only"))
    first = True
    for kind, title in groups:
        members = [key for key in keys if results[key]["status"] == kind]
        if not members:
            continue
        if not first:
            lines.append("\\addlinespace[6pt]")
        first = False
        noun = "result" if len(members) == 1 else "results"
        lines.append(f"\\multicolumn{{2}}{{@{{}}l}}{{\\emph{{{title} "
                     f"({len(members)} {noun})}}}}\\\\[3pt]")
        for key in members:
            result = results[key]
            phrase = result.get("summary") or result.get("abstract") or result["boundary"]
            if kind == "lean":
                modules = [path[len(prefix):] for path in result["evidence"]
                           if path.startswith(prefix)]
                cell = ("\\newline ".join(f"\\path{{{module}}}" for module in modules)
                        or "See \\cref{sec:verification}")
            else:
                cell = _proof_location(result["evidence"], texts or {})
            lines.append(f"{_sentence_case(phrase)} & {cell}\\\\[2pt]")
    lines += ["\\bottomrule", "\\end{longtable}"]
    return "\n".join(lines)


